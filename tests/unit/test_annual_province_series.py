from __future__ import annotations

import tempfile
import unittest
from decimal import Decimal
from pathlib import Path

from ecadin_energy.data_processing.cleaning.annual_province_series import (
    extract_filename_year,
    format_decimal,
    parse_decimal,
)


class AnnualProvinceSeriesTest(unittest.TestCase):
    def test_parse_missing_markers(self) -> None:
        for value in ["", "-", "–", "—"]:
            self.assertIsNone(parse_decimal(value, context="unit test"))

    def test_parse_numeric(self) -> None:
        self.assertEqual(parse_decimal("123.45", context="unit test"), Decimal("123.45"))

    def test_reject_negative_numeric(self) -> None:
        with self.assertRaises(ValueError):
            parse_decimal("-1.00", context="unit test")

    def test_extract_filename_year(self) -> None:
        path = Path("Electricity Generated by Province, 2024.csv")
        self.assertEqual(extract_filename_year(path), 2024)

    def test_format_decimal(self) -> None:
        self.assertEqual(format_decimal(Decimal("123.456")), "123.46")
        self.assertEqual(format_decimal(None), "")


if __name__ == "__main__":
    unittest.main()
