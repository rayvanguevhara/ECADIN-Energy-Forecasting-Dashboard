from __future__ import annotations

import csv
import tempfile
import unittest
from decimal import Decimal
from pathlib import Path

from ecadin_energy.data_processing.cleaning.annual_province_series import (
    extract_filename_year,
    format_decimal,
    parse_decimal,
    read_annual_province_file,
)
from ecadin_energy.data_processing.harmonization.regions import clear_reference_caches


def _seed_custom_reference(
    root: Path,
    *,
    regions: list[dict[str, str]],
    aliases: list[dict[str, str]],
) -> None:
    ref_dir = root / "data" / "reference"
    ref_dir.mkdir(parents=True, exist_ok=True)
    with (ref_dir / "regions.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=["region_id", "canonical_region_name", "modeling_order"],
            lineterminator="\r\n",
        )
        writer.writeheader()
        writer.writerows(regions)
    with (ref_dir / "region_aliases.csv").open(
        "w", encoding="utf-8-sig", newline=""
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "alias_id",
                "source_scope",
                "source_region_name",
                "normalized_alias",
                "region_id",
                "canonical_region_name",
                "mapping_type",
                "aggregation_rule",
                "included_as_separate_model_region",
                "priority",
                "effective_start_year",
                "effective_end_year",
                "notes",
            ],
            lineterminator="\r\n",
        )
        writer.writeheader()
        writer.writerows(aliases)


def _write_province_csv(
    path: Path,
    *,
    unit_row: str,
    year: int,
    rows: list[tuple[str, str]],
) -> None:
    lines = [
        "Province,",
        f",{unit_row}",
        f",{year}",
        *(f"{name},{value}" for name, value in rows),
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")


class AnnualProvinceSeriesTest(unittest.TestCase):
    def tearDown(self) -> None:
        clear_reference_caches()

    def test_parse_missing_markers(self) -> None:
        for value in ["", "-", "–", "—", "...", "…"]:
            self.assertIsNone(parse_decimal(value, context="unit test"))

    def test_parse_numeric(self) -> None:
        self.assertEqual(parse_decimal("123.45", context="unit test"), Decimal("123.45"))

    def test_reject_negative_numeric(self) -> None:
        with self.assertRaises(ValueError):
            parse_decimal("-1.00", context="unit test")

    def test_extract_filename_year(self) -> None:
        path = Path("Electricity Generated by Province, 2024.csv")
        self.assertEqual(extract_filename_year(path), 2024)

    def test_format_decimal(self) -> None:
        self.assertEqual(format_decimal(Decimal("123.456")), "123.46")
        self.assertEqual(format_decimal(None), "")

    def test_read_annual_province_file_validates_unit_token(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _seed_custom_reference(
                root,
                regions=[
                    {"region_id": "AC", "canonical_region_name": "ACEH", "modeling_order": "1"}
                ],
                aliases=[
                    {
                        "alias_id": "A001",
                        "source_scope": "all_sources",
                        "source_region_name": "ACEH",
                        "normalized_alias": "ACEH",
                        "region_id": "AC",
                        "canonical_region_name": "ACEH",
                        "mapping_type": "identity",
                        "aggregation_rule": "none",
                        "included_as_separate_model_region": "True",
                        "priority": "100",
                        "effective_start_year": "",
                        "effective_end_year": "",
                        "notes": "",
                    }
                ],
            )
            csv_path = root / "Series, 2024.csv"
            _write_province_csv(
                csv_path,
                unit_row="Electricity Generated by Province (GWh)",
                year=2024,
                rows=[("ACEH", "10.50"), ("INDONESIA", "10.50")],
            )

            parsed = read_annual_province_file(
                csv_path,
                expected_source_rows=1,
                expected_unit_token="(GWh)",
                project_root=root,
            )
            self.assertEqual(parsed.values_by_region_id["AC"], Decimal("10.50"))

            with self.assertRaisesRegex(ValueError, "Expected unit token"):
                read_annual_province_file(
                    csv_path,
                    expected_source_rows=1,
                    expected_unit_token="(Mega Watt)",
                    project_root=root,
                )

    def test_read_annual_province_file_validates_aggregation_rule(self) -> None:
        clear_reference_caches()
        parent_alias = {
            "alias_id": "A024",
            "source_scope": "all_sources",
            "source_region_name": "PAPUA",
            "normalized_alias": "PAPUA",
            "region_id": "PA",
            "canonical_region_name": "PAPUA",
            "mapping_type": "identity",
            "aggregation_rule": "none",
            "included_as_separate_model_region": "True",
            "priority": "100",
            "effective_start_year": "",
            "effective_end_year": "",
            "notes": "",
        }
        regions = [{"region_id": "PA", "canonical_region_name": "PAPUA", "modeling_order": "1"}]

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _seed_custom_reference(
                root,
                regions=regions,
                aliases=[
                    parent_alias,
                    {
                        **parent_alias,
                        "alias_id": "A037",
                        "source_scope": "population_pdrb_and_modern_province_sources",
                        "source_region_name": "PAPUA SELATAN",
                        "normalized_alias": "PAPUA SELATAN",
                        "mapping_type": "aggregate_to_model_region",
                        "aggregation_rule": "sum_by_region_id_year",
                        "included_as_separate_model_region": "False",
                        "priority": "95",
                    },
                ],
            )
            csv_path = root / "Series, 2024.csv"
            _write_province_csv(
                csv_path,
                unit_row="Metric (GWh)",
                year=2024,
                rows=[("PAPUA", "100.00"), ("PAPUA SELATAN", "25.00"), ("INDONESIA", "125.00")],
            )
            parsed = read_annual_province_file(
                csv_path,
                expected_source_rows=2,
                expected_unit_token="(GWh)",
                project_root=root,
            )
            self.assertEqual(parsed.values_by_region_id["PA"], Decimal("125.00"))
            self.assertEqual(parsed.source_contributors_by_region_id["PA"], 2)

        clear_reference_caches()
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _seed_custom_reference(
                root,
                regions=regions,
                aliases=[
                    parent_alias,
                    {
                        **parent_alias,
                        "alias_id": "A099",
                        "source_region_name": "PAPUA SELATAN",
                        "normalized_alias": "PAPUA SELATAN",
                        "mapping_type": "rename",
                        "aggregation_rule": "none",
                        "priority": "90",
                    },
                ],
            )
            csv_path = root / "Series, 2024.csv"
            _write_province_csv(
                csv_path,
                unit_row="Metric (GWh)",
                year=2024,
                rows=[("PAPUA", "100.00"), ("PAPUA SELATAN", "25.00"), ("INDONESIA", "125.00")],
            )
            with self.assertRaisesRegex(ValueError, "sum_by_region_id_year"):
                read_annual_province_file(
                    csv_path,
                    expected_source_rows=2,
                    project_root=root,
                )

        clear_reference_caches()
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _seed_custom_reference(
                root,
                regions=regions,
                aliases=[{**parent_alias, "aggregation_rule": "mean"}],
            )
            csv_path = root / "Series, 2024.csv"
            _write_province_csv(
                csv_path,
                unit_row="Metric (GWh)",
                year=2024,
                rows=[("PAPUA", "100.00"), ("INDONESIA", "100.00")],
            )
            with self.assertRaisesRegex(ValueError, "Unsupported aggregation rule"):
                read_annual_province_file(
                    csv_path,
                    expected_source_rows=1,
                    project_root=root,
                )

    def test_read_annual_province_file_validates_effective_years(self) -> None:
        clear_reference_caches()
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            _seed_custom_reference(
                root,
                regions=[
                    {"region_id": "PA", "canonical_region_name": "PAPUA", "modeling_order": "1"}
                ],
                aliases=[
                    {
                        "alias_id": "A037",
                        "source_scope": "all_sources",
                        "source_region_name": "PAPUA SELATAN",
                        "normalized_alias": "PAPUA SELATAN",
                        "region_id": "PA",
                        "canonical_region_name": "PAPUA",
                        "mapping_type": "aggregate_to_model_region",
                        "aggregation_rule": "sum_by_region_id_year",
                        "included_as_separate_model_region": "False",
                        "priority": "95",
                        "effective_start_year": "2023",
                        "effective_end_year": "2024",
                        "notes": "",
                    }
                ],
            )

            path_2022_missing = root / "Series, 2022.csv"
            _write_province_csv(
                path_2022_missing,
                unit_row="Metric (GWh)",
                year=2022,
                rows=[("PAPUA SELATAN", "-"), ("INDONESIA", "0")],
            )
            parsed_missing = read_annual_province_file(
                path_2022_missing,
                expected_source_rows=1,
                project_root=root,
            )
            self.assertEqual(parsed_missing.missing_source_names, ("PAPUA SELATAN",))

            _write_province_csv(
                path_2022_missing,
                unit_row="Metric (GWh)",
                year=2022,
                rows=[("PAPUA SELATAN", "10.00"), ("INDONESIA", "10.00")],
            )
            with self.assertRaisesRegex(ValueError, "effective_start_year=2023"):
                read_annual_province_file(
                    path_2022_missing,
                    expected_source_rows=1,
                    project_root=root,
                )

            path_2023 = root / "Series, 2023.csv"
            _write_province_csv(
                path_2023,
                unit_row="Metric (GWh)",
                year=2023,
                rows=[("PAPUA SELATAN", "217.92"), ("INDONESIA", "217.92")],
            )
            parsed_2023 = read_annual_province_file(
                path_2023,
                expected_source_rows=1,
                project_root=root,
            )
            self.assertEqual(parsed_2023.values_by_region_id["PA"], Decimal("217.92"))

            path_2025 = root / "Series, 2025.csv"
            _write_province_csv(
                path_2025,
                unit_row="Metric (GWh)",
                year=2025,
                rows=[("PAPUA SELATAN", "50.00"), ("INDONESIA", "50.00")],
            )
            with self.assertRaisesRegex(ValueError, "effective_end_year=2024"):
                read_annual_province_file(
                    path_2025,
                    expected_source_rows=1,
                    project_root=root,
                )


if __name__ == "__main__":
    unittest.main()
